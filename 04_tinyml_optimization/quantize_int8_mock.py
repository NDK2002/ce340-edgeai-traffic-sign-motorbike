"""[S2] Mock TinyML Optimization Pipeline: Pruning + Full Integer INT8 & C-array export.

Chạy độc lập bằng model CNN tối giản (tương thích tflite-micro) và 5 ảnh mock
trong `01_dataset/mock_assets/images/`. Khuyến nghị chạy trên Google Colab (Linux)
hoặc môi trường Python đã cài đúng `requirements.txt`.
"""

from __future__ import annotations

import argparse
import os
from pathlib import Path

# Bắt buộc đặt trước khi import TensorFlow để TFMOT dùng legacy Keras 2 API
os.environ.setdefault("TF_USE_LEGACY_KERAS", "1")


def export_tflite_to_c_header(
    tflite_bytes: bytes,
    output_header: Path,
    array_name: str = "g_tinyml_mock_model_int8",
    guard_name: str = "CE340_TINYML_MOCK_MODEL_INT8_H_",
) -> None:
    """Chuyển bytes của file .tflite thành mảng C-array alignas(16) cho ESP32-S3."""
    output_header.parent.mkdir(parents=True, exist_ok=True)
    hex_bytes = [f"0x{b:02x}" for b in tflite_bytes]
    lines = [
        f"#ifndef {guard_name}",
        f"#define {guard_name}",
        "",
        "// Auto-generated by 04_tinyml_optimization/quantize_int8_mock.py",
        "// Full-Integer INT8 TFLite model for ESP32-S3 (tflite-micro)",
        f"alignas(16) const unsigned char {array_name}[] = {{",
    ]
    for idx in range(0, len(hex_bytes), 12):
        chunk = ", ".join(hex_bytes[idx : idx + 12])
        comma = "," if idx + 12 < len(hex_bytes) else ""
        lines.append(f"  {chunk}{comma}")
    lines.extend(
        [
            "};",
            f"const unsigned int {array_name}_len = {len(tflite_bytes)};",
            "",
            "// Compatibility aliases for firmware models.h",
            "#ifndef g_mock_model_int8",
            f"#define g_mock_model_int8 {array_name}",
            f"#define g_mock_model_int8_len {array_name}_len",
            "#endif",
            "",
            f"#endif  // {guard_name}",
            "",
        ]
    )
    output_header.write_text("\n".join(lines), encoding="utf-8")


def _load_calibration_images(mock_images_dir: Path, imgsz: int) -> "np.ndarray":
    """Đọc ảnh mock và chuẩn hóa RGB float32 về [-1, 1] (khớp MobileNetV2-SSD)."""
    import numpy as np
    from PIL import Image

    image_paths = sorted(mock_images_dir.glob("*.jpg"))
    if not image_paths:
        raise FileNotFoundError(f"Không tìm thấy ảnh .jpg trong: {mock_images_dir}")

    batch = []
    for path in image_paths:
        with Image.open(path) as img:
            resized = img.convert("RGB").resize((imgsz, imgsz))
            arr = np.asarray(resized, dtype=np.float32) / 127.5 - 1.0
            batch.append(arr)
    return np.stack(batch, axis=0)


def _build_mock_cnn(imgsz: int, num_classes: int):
    """Dựng CNN tối giản dùng các layer chuẩn tflite-micro (ESP-NN safe)."""
    import tensorflow as tf

    inputs = tf.keras.Input(shape=(imgsz, imgsz, 3), name="input_rgb")
    x = tf.keras.layers.Conv2D(16, 3, strides=2, padding="same", activation="relu")(inputs)
    x = tf.keras.layers.DepthwiseConv2D(3, strides=2, padding="same", activation="relu")(x)
    x = tf.keras.layers.Conv2D(32, 1, padding="same", activation="relu")(x)
    x = tf.keras.layers.DepthwiseConv2D(3, strides=2, padding="same", activation="relu")(x)
    x = tf.keras.layers.Conv2D(64, 1, padding="same", activation="relu")(x)
    x = tf.keras.layers.GlobalAveragePooling2D()(x)
    outputs = tf.keras.layers.Dense(num_classes, name="logits")(x)
    return tf.keras.Model(inputs=inputs, outputs=outputs, name="tinyml_mock_cnn")


def _prune_and_strip(model, calib_images: "np.ndarray", num_classes: int, epochs: int):
    """Áp dụng TFMOT magnitude pruning và strip wrapper trước khi convert TFLite."""
    import numpy as np
    import tensorflow as tf
    import tensorflow_model_optimization as tfmot

    pruning_params = {
        "pruning_schedule": tfmot.sparsity.keras.PolynomialDecay(
            initial_sparsity=0.0,
            final_sparsity=0.50,
            begin_step=0,
            end_step=max(1, epochs * len(calib_images)),
        )
    }
    pruned_model = tfmot.sparsity.keras.prune_low_magnitude(model, **pruning_params)
    pruned_model.compile(
        optimizer="adam",
        loss=tf.keras.losses.SparseCategoricalCrossentropy(from_logits=True),
    )

    dummy_labels = np.arange(len(calib_images)) % num_classes
    pruned_model.fit(
        calib_images,
        dummy_labels,
        batch_size=len(calib_images),
        epochs=epochs,
        callbacks=[tfmot.sparsity.keras.UpdatePruningStep()],
        verbose=0,
    )
    return tfmot.sparsity.keras.strip_pruning(pruned_model)


def _convert_fp32_and_int8(stripped_model, calib_images: "np.ndarray") -> tuple[bytes, bytes]:
    """Export bản FP32 đối chứng và bản Full Integer INT8."""
    import tensorflow as tf

    fp32_converter = tf.lite.TFLiteConverter.from_keras_model(stripped_model)
    fp32_bytes = fp32_converter.convert()

    def representative_dataset():
        for i in range(len(calib_images)):
            yield [calib_images[i : i + 1]]

    int8_converter = tf.lite.TFLiteConverter.from_keras_model(stripped_model)
    int8_converter.optimizations = [tf.lite.Optimize.DEFAULT]
    int8_converter.representative_dataset = representative_dataset
    int8_converter.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    int8_converter.inference_input_type = tf.int8
    int8_converter.inference_output_type = tf.int8
    int8_bytes = int8_converter.convert()
    return fp32_bytes, int8_bytes


def _verify_int8_interpreter(int8_bytes: bytes) -> None:
    """Kiểm tra tensor I/O là int8 và chạy thử 1 lượt suy luận."""
    import numpy as np
    import tensorflow as tf

    interpreter = tf.lite.Interpreter(model_content=int8_bytes)
    interpreter.allocate_tensors()
    in_detail = interpreter.get_input_details()[0]
    out_detail = interpreter.get_output_details()[0]

    assert in_detail["dtype"] == np.int8, f"Expected int8 input, got {in_detail['dtype']}"
    assert out_detail["dtype"] == np.int8, f"Expected int8 output, got {out_detail['dtype']}"

    sample = np.zeros(in_detail["shape"], dtype=np.int8)
    interpreter.set_tensor(in_detail["index"], sample)
    interpreter.invoke()
    output = interpreter.get_tensor(out_detail["index"])

    print(
        f"[Verify] Input: {tuple(in_detail['shape'])} {in_detail['dtype'].__name__} | "
        f"Output: {tuple(output.shape)} {out_detail['dtype'].__name__}"
    )


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Mock Pruning + Full INT8 pipeline (CE340)")
    parser.add_argument("--imgsz", type=int, default=160, help="Kích thước ảnh đầu vào (mặc định: 160)")
    parser.add_argument("--num-classes", type=int, default=12, help="Số lớp biển báo (mặc định: 12)")
    parser.add_argument("--epochs", type=int, default=2, help="Số epoch mock để cập nhật pruning step")
    parser.add_argument(
        "--mock-images",
        type=Path,
        default=Path("01_dataset/mock_assets/images"),
        help="Thư mục ảnh calibration mock",
    )
    parser.add_argument(
        "--output-header",
        type=Path,
        default=Path("04_tinyml_optimization/mock_model_int8.h"),
        help="Đường dẫn file C-array .h đầu ra",
    )
    parser.add_argument(
        "--export-header-only-from-tflite",
        type=Path,
        default=None,
        help="Chỉ convert file .tflite có sẵn sang .h (dùng khi máy chưa cài TensorFlow)",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()

    if args.export_header_only_from_tflite is not None:
        tflite_bytes = args.export_header_only_from_tflite.read_bytes()
        export_tflite_to_c_header(tflite_bytes, args.output_header)
        print(f"[Header-Only] Exported {len(tflite_bytes)} bytes -> {args.output_header}")
        return

    calib_images = _load_calibration_images(args.mock_images, args.imgsz)
    base_model = _build_mock_cnn(args.imgsz, args.num_classes)
    stripped_model = _prune_and_strip(base_model, calib_images, args.num_classes, args.epochs)
    fp32_bytes, int8_bytes = _convert_fp32_and_int8(stripped_model, calib_images)

    reduction_pct = (1.0 - len(int8_bytes) / len(fp32_bytes)) * 100.0
    print(f"[Size] FP32: {len(fp32_bytes):,} bytes | INT8: {len(int8_bytes):,} bytes")
    print(f"[Size] Compression reduction: {reduction_pct:.2f}% (target >= 70%)")
    assert reduction_pct >= 70.0, f"Compression {reduction_pct:.2f}% < 70% target"

    _verify_int8_interpreter(int8_bytes)
    export_tflite_to_c_header(int8_bytes, args.output_header)
    print(f"[Done] Saved C-array header to: {args.output_header}")


if __name__ == "__main__":
    main()
